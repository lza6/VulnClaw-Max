_VARIANT_TEMPLATES: dict[str, dict[str, str]] = {
    "executive": {"zh": EXECUTIVE_TEMPLATE, "en": EXECUTIVE_TEMPLATE_EN},
    "ctf": {"zh": CTF_TEMPLATE, "en": CTF_TEMPLATE_EN},
}


def normalize_template(template: str | None) -> str:
    """Return a known template kind, rejecting unknown values loudly."""
    kind = (template or "pentest").strip().lower()
    if kind not in REPORT_TEMPLATE_KINDS:
        raise ValueError(
            f"unknown report template {template!r}; expected one of {', '.join(REPORT_TEMPLATE_KINDS)}"
        )
    return kind


def select_variant_template(template: str) -> str:
    """Return the localized template source for a non-``pentest`` kind."""
    kind = normalize_template(template)
    variants = _VARIANT_TEMPLATES.get(kind)
    if variants is None:
        raise ValueError(f"template {kind!r} has no variant source; it is the default pentest template")
    return variants["en" if current_lang() == "en" else "zh"]


def includes_reproduction_details(template: str) -> bool:
    """Executive summaries intentionally omit location/PoC reproduction blocks."""
    return normalize_template(template) != "executive"
